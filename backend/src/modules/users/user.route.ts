import { Router } from "express";
import { UserController } from "./controller/user.controller.js";
import { authMiddleware, requireRole } from "../../middlewares/auth.middleware.js";
import { loginLimit, registerLimit } from "../../middlewares/request-security.js";
const router = Router();
const controller = new UserController();
router.use((_req, res, next) => { res.set("Cache-Control", "no-store"); next(); });
router.post("/", registerLimit, controller.create);
router.post("/login", loginLimit, controller.login);
router.post("/logout", controller.logout);
router.get("/me", authMiddleware, controller.getMe);
router.patch("/me", authMiddleware, controller.updateProfile);
router.patch("/me/password", loginLimit, authMiddleware, controller.changePassword);
router.get("/", authMiddleware, requireRole("manager", "owner"), controller.getAll);
router.get("/:id", authMiddleware, requireRole("manager", "owner"), controller.getById);
router.delete("/:id", authMiddleware, requireRole("owner"), controller.delete);
export default router;
